#!/usr/bin/env bash
# Builds a .deb from a prebuilt wpr binary:
#   packaging/linux/build-deb.sh ARCH VERSION WPR_BINARY OUT_DIR
# ARCH is the Debian architecture (amd64, arm64). Needs dpkg-deb.
set -euo pipefail
arch="$1"; version="$2"; bin="$3"; out="$4"
here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "$here/../.." && pwd)"
tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
pkg="$tmp/pkg"
install -d "$pkg/DEBIAN" "$pkg/usr/bin" "$pkg/lib/systemd/system" "$pkg/etc/default" "$pkg/usr/share/doc/spmag-wpr"
install -m 755 "$bin" "$pkg/usr/bin/wpr"
install -m 644 "$here/deb/spmag-wpr.service" "$pkg/lib/systemd/system/spmag-wpr.service"
install -m 644 "$here/deb/spmag-wpr.default" "$pkg/etc/default/spmag-wpr"
install -m 644 "$root/LICENSE" "$pkg/usr/share/doc/spmag-wpr/copyright"
install -m 644 "$root/README.md" "$pkg/usr/share/doc/spmag-wpr/README.md"
for s in postinst prerm postrm; do install -m 755 "$here/deb/$s" "$pkg/DEBIAN/$s"; done
echo /etc/default/spmag-wpr > "$pkg/DEBIAN/conffiles"
size=$(du -sk "$pkg" | cut -f1)
cat > "$pkg/DEBIAN/control" <<CTRL
Package: spmag-wpr
Version: $version
Architecture: $arch
Maintainer: AspidovSS <aspidovss@users.noreply.github.com>
Installed-Size: $size
Section: graphics
Priority: optional
Homepage: https://github.com/aspidovss/spmag-sony-pm-alt-gui
Description: Receive photos from Sony cameras over Wi-Fi (Send to Computer)
 SPMAG Wifi Photo Receiver: a replacement for the Wi-Fi import of Sony
 PlayMemories Home. Runs as a service, downloads the files that are not on
 this computer yet and offers an optional browser interface (wpr watch -web).
 All code and text were generated by an AI model; see the README.
CTRL
mkdir -p "$out"
dpkg-deb --root-owner-group --build "$pkg" "$out/spmag-wpr_${version}_${arch}.deb" >/dev/null
echo "built $out/spmag-wpr_${version}_${arch}.deb"
